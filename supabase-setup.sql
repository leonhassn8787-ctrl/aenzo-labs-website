-- AENZO LABS site content table
-- Run in Supabase Dashboard > SQL Editor.
create table if not exists public.site_posts (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 1 and 140),
  kind text not null default 'Announcement',
  link text,
  body text not null check (char_length(body) between 1 and 5000),
  published boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.site_posts enable row level security;
-- Public visitors may read published posts only.
drop policy if exists "Public can read published posts" on public.site_posts;
create policy "Public can read published posts" on public.site_posts
for select to anon, authenticated using (published = true);
-- Authenticated users may manage posts. Restrict admin access further in Supabase
-- Auth / policies before inviting any other users.
drop policy if exists "Authenticated users can insert posts" on public.site_posts;
create policy "Authenticated users can insert posts" on public.site_posts
for insert to authenticated with check (true);
drop policy if exists "Authenticated users can update posts" on public.site_posts;
create policy "Authenticated users can update posts" on public.site_posts
for update to authenticated using (true) with check (true);
drop policy if exists "Authenticated users can delete posts" on public.site_posts;
create policy "Authenticated users can delete posts" on public.site_posts
for delete to authenticated using (true);
grant select on public.site_posts to anon, authenticated;
grant insert, update, delete on public.site_posts to authenticated;
grant usage, select on sequence public.site_posts_id_seq to authenticated;
