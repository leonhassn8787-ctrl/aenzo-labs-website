-- Run in Supabase Dashboard > SQL Editor.
-- Then create your admin in Authentication > Users and authorize that user
-- by inserting their UUID into public.admin_users (see instructions below).

create table if not exists public.site_posts (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(title) between 1 and 140),
  kind text not null default 'Announcement',
  link text,
  body text not null check (char_length(body) between 1 and 5000),
  published boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

alter table public.site_posts enable row level security;
alter table public.admin_users enable row level security;

drop policy if exists "Public can read published posts" on public.site_posts;
create policy "Public can read published posts"
on public.site_posts for select to anon, authenticated
using (published = true);

drop policy if exists "Admins can insert posts" on public.site_posts;
create policy "Admins can insert posts"
on public.site_posts for insert to authenticated
with check (exists (select 1 from public.admin_users a where a.user_id = auth.uid()));

drop policy if exists "Admins can update posts" on public.site_posts;
create policy "Admins can update posts"
on public.site_posts for update to authenticated
using (exists (select 1 from public.admin_users a where a.user_id = auth.uid()))
with check (exists (select 1 from public.admin_users a where a.user_id = auth.uid()));

drop policy if exists "Admins can delete posts" on public.site_posts;
create policy "Admins can delete posts"
on public.site_posts for delete to authenticated
using (exists (select 1 from public.admin_users a where a.user_id = auth.uid()));

drop policy if exists "Users can read own admin record" on public.admin_users;
create policy "Users can read own admin record"
on public.admin_users for select to authenticated
using (user_id = auth.uid());

grant select on public.site_posts to anon, authenticated;
grant insert, update, delete on public.site_posts to authenticated;
grant select on public.admin_users to authenticated;
grant usage, select on sequence public.site_posts_id_seq to authenticated;

